-- Topic: Reading the write-ahead log position and XID age - first checks after a crash
-- Database: PostgreSQL 14+
-- Problem: After an unexpected restart, a DBA needs three facts fast: where the WAL is now,
--          how much WAL a workload generates, and how close the database is to transaction
--          ID wraparound. This file shows the catalog queries that answer them.
-- Note: This is the SQL side only. Decoding WAL records themselves is done outside SQL
--       with pg_waldump (or the pg_walinspect extension in PostgreSQL 15+), e.g.:
--         pg_waldump --start=<lsn> --path=$PGDATA/pg_wal
-- All data is fictional.

-- 1) Current WAL position and the segment file it lives in
SELECT pg_current_wal_lsn()                          AS current_lsn,
       pg_walfile_name(pg_current_wal_lsn())         AS current_wal_file;

-- 2) How much WAL a piece of work generates: measure LSN before and after
DROP TABLE IF EXISTS wal_probe;
CREATE TABLE wal_probe (id int, payload text);

DO $$
DECLARE
    lsn_before pg_lsn := pg_current_wal_insert_lsn();   -- insert position, includes unflushed WAL
BEGIN
    INSERT INTO wal_probe SELECT g, repeat('x', 100) FROM generate_series(1, 10000) g;
    RAISE NOTICE 'WAL generated by 10,000 inserts: %',
        pg_size_pretty(pg_wal_lsn_diff(pg_current_wal_insert_lsn(), lsn_before));
END $$;

-- 3) Transaction ID wraparound margin (autovacuum must freeze before this reaches 0)
SELECT datname,
       age(datfrozenxid)                              AS xid_age,
       2147483648 - age(datfrozenxid)                 AS xids_until_wraparound,
       round(100.0 * age(datfrozenxid) / 2147483648, 2) AS pct_used
FROM pg_database
ORDER BY xid_age DESC;

-- Expected: an LSN like 0/1A2B3C4D, a NOTICE with a few MB of WAL, and pct_used well
-- under 10% on a healthy test database.
